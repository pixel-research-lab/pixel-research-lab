PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS flows (
 state TEXT PRIMARY KEY, uid TEXT NOT NULL, dm INTEGER NOT NULL, expires INTEGER NOT NULL,
 ticket TEXT UNIQUE, code TEXT
);
CREATE INDEX IF NOT EXISTS flows_expiry ON flows(expires);
CREATE INDEX IF NOT EXISTS flows_owner ON flows(uid);
CREATE TABLE IF NOT EXISTS links (
 uid TEXT PRIMARY KEY, team TEXT NOT NULL, member TEXT NOT NULL, channel TEXT NOT NULL,
 channel_name TEXT NOT NULL, dm INTEGER NOT NULL, secret TEXT NOT NULL, generation TEXT NOT NULL, linked_at INTEGER NOT NULL,
 UNIQUE(team, member)
);
CREATE TABLE IF NOT EXISTS notices (
 uid TEXT NOT NULL REFERENCES links(uid) ON DELETE CASCADE, generation TEXT NOT NULL,
 id TEXT NOT NULL, kind TEXT NOT NULL, label TEXT NOT NULL, at INTEGER NOT NULL, url TEXT NOT NULL,
 seen INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(uid,generation,id)
);
CREATE INDEX IF NOT EXISTS notices_feed ON notices(uid,generation,at DESC);

CREATE TABLE IF NOT EXISTS inbox (
 id TEXT PRIMARY KEY, team TEXT NOT NULL, channel TEXT NOT NULL, sender TEXT NOT NULL, ts TEXT NOT NULL,
 kind TEXT NOT NULL, at INTEGER NOT NULL, next INTEGER NOT NULL DEFAULT 0, cursor TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS inbox_due ON inbox(next);
